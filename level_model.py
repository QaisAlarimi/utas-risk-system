"""Risk-LEVEL model trained by the team in Colab (campus_risk_model_final.joblib, sklearn 1.6.1).
Trained on PROVISIONAL labels (generated by a likelihood x severity rule, synthetic, not expert-approved), so it
mostly re-learns that rule. It is shown to the admin as a provisional suggestion only; the human decides.
It needs the reporter's likelihood AND severity estimates; without them no suggestion is made."""
import os
import pandas as pd
import config

PATH = os.path.join(config.MODEL_DIR, "campus_risk_level_model.joblib")
CAT = ["building_id", "floor", "location_type", "risk_category_code", "risk_subtype_code", "people_exposed_band",
       "exposure_frequency", "existing_controls", "visible_damage", "hazard_active", "reporter_urgency"]
NUM = ["likelihood_reported", "severity_reported", "risk_product", "likelihood_missing", "severity_missing"]
_cache = {}


def _load():
    if "p" not in _cache:
        try:
            import joblib
            _cache["p"] = joblib.load(PATH)
        except Exception as e:          # e.g. scikit-learn version mismatch -> feature simply switched off
            _cache["p"] = None
            _cache["err"] = str(e)[:200]
    return _cache["p"]


def available():
    return _load() is not None


def predict(r: dict):
    """r: building, floor, location_type, category, subtype, people, frequency, controls, damage, hazard, urgency,
    likelihood, severity, text.  Returns (level, confidence) or None."""
    p = _load()
    if p is None or not r.get("likelihood") or not r.get("severity"):
        return None
    d = pd.DataFrame([{
        "building_id": r.get("building"), "floor": r.get("floor"), "location_type": r.get("location_type"),
        "risk_category_code": r.get("category"), "risk_subtype_code": r.get("subtype"),
        "people_exposed_band": r.get("people"), "exposure_frequency": r.get("frequency"),
        "existing_controls": r.get("controls"), "visible_damage": r.get("damage"), "hazard_active": r.get("hazard"),
        "reporter_urgency": r.get("urgency"), "likelihood_reported": r["likelihood"], "severity_reported": r["severity"],
        "risk_description": r.get("text") or ""}])
    d["risk_product"] = d.likelihood_reported * d.severity_reported
    d["likelihood_missing"] = 0
    d["severity_missing"] = 0
    for c in CAT:
        d[c] = d[c].fillna("Unknown").astype(str)
    for c in NUM:
        d[c] = pd.to_numeric(d[c], errors="coerce").astype("float64")
    m = p["model"]
    prob = m.predict_proba(d)[0]
    i = int(prob.argmax())
    return str(m.classes_[i]), float(prob[i])
